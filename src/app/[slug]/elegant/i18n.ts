type Dict = typeof translations.sl;
export type ElegantKey = keyof Dict;

/** Text for `key` in `lang` (Slovenian when the language is unknown). */
export function t<K extends ElegantKey>(lang: SupportedLanguage | undefined, key: K): Dict[K] {
  const dict = (translations[lang ?? 'sl'] ?? translations.sl) as unknown as Dict;
  if (key === 'stepDateTime' && isRequestMode()) return REQUEST_TEXT[lang === 'en' ? 'en' : 'sl'].stepLabel as Dict[K];
  return dict[key];
}

/** Date pattern for the language: Slovenian "28. oktober", English "28 October". */
export function datePattern(lang: SupportedLanguage | undefined, pattern: string): string {
  return lang === 'en' ? pattern.replace('d. ', 'd ') : pattern;
}

/** date-fns locale for the language. */
export function dateLocale(lang: SupportedLanguage | undefined) {
  return lang === 'en' ? enUS : sl;
}
